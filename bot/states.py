"""FSM-состояния диалогов бота.

Управление идёт кнопками (callback'ами), но шаги, где нужен свободный ввод
(URL и токен панели, IP, логин, пароль, домен), остаются текстовыми — их и
описывают состояния ниже. Шаги с выбором (режим панели, способ доступа,
inbound'ы, сквады, подтверждение) тоже привязаны к состояниям, чтобы нажатия
кнопок применялись только на своём шаге.

Развилка аутентификации (ADR 0002): доступ по паролю (низкий порог) или по
публичному ключу / one-liner (выше доверие). Логин спрашиваем до развилки — он
нужен обеим веткам. Обе сходятся в выбор inbound'ов (ADR 0005) и постановку
задачи оркестратору.
"""
from aiogram.fsm.state import State, StatesGroup


class AddNode(StatesGroup):
    # Выбор: подключить существующую панель или развернуть с нуля (ADR 0001)
    choose_panel_mode = State()
    wait_panel_url = State()
    wait_panel_token = State()

    # Данные сервера
    wait_ip = State()
    wait_login = State()       # логин нужен обеим веткам доступа
    choose_auth = State()      # пароль | ключ (ADR 0002)
    wait_password = State()    # только для ветки «пароль»; не логируется, не хранится
    wait_key_added = State()   # ветка «ключ»: ждём, пока оператор добавит наш pubkey

    # Набор inbound'ов профиля (ADR 0005): мультивыбор кнопками-тоглами
    choose_inbounds = State()
    wait_domain = State()      # только если выбран TLS-инбаунд: домен оператора

    # Параметры профиля
    wait_reality_dest = State()  # донор Reality per-node (ADR 0007); есть дефолт
    wait_country = State()       # код страны ноды (ISO-2) для create_node

    # Куда подключить ноду, чтобы её увидели пользователи (ADR 0008): список
    # внутренних сквадов тянем из панели, оператор выбирает тоглами (дефолт — все).
    choose_squads = State()

    confirm = State()


class SetPanel(StatesGroup):
    """Привязка/смена сохранённой панели (раздел «Панель» в меню).

    Панель вводится один раз и переиспользуется на каждом добавлении ноды
    (ADR 0003, single-tenant). Этот мини-диалог задаёт другую панель, не трогая
    мастер добавления."""
    wait_url = State()
    wait_token = State()
